// Writes functions/_config.ts from the build's .env file, so the link-preview function can read the public payment
// page data. Only public values (the project URL and anon key the web app ships). The file is not committed.
import { readFileSync, writeFileSync } from 'node:fs';

const mode = process.argv[2] ?? 'production';
const env = Object.fromEntries(readFileSync(`.env.${mode}`, 'utf8').split('\n')
  .map(l => l.match(/^\s*([A-Z_]+)\s*=\s*(.*?)\s*$/)).filter(Boolean).map(m => [m[1], m[2].replace(/^["']|["']$/g, '')]));
if (!env.VITE_SUPABASE_URL || !env.VITE_SUPABASE_ANON_KEY) throw new Error(`.env.${mode} needs VITE_SUPABASE_URL and VITE_SUPABASE_ANON_KEY`);
writeFileSync('functions/_config.ts', `// Generated by scripts/function-config.mjs from .env.${mode}. Not committed.
export const SUPABASE_URL = ${JSON.stringify(env.VITE_SUPABASE_URL)};
export const SUPABASE_ANON_KEY = ${JSON.stringify(env.VITE_SUPABASE_ANON_KEY)};
export const DEFAULT_ORG = ${JSON.stringify(env.VITE_DEFAULT_ORG ?? '')};
`);
