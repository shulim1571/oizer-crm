// Builds the help assistant's guide (supabase/functions/_shared/assistantGuide.ts) from the app itself:
// docs/assistant-guide.md (written for staff), the sidebar menu in src/components/Layout.tsx and every form
// field's label and help in src/lib/schemas.ts. Run: node scripts/build-assistant-guide.mjs  (a test checks the
// committed file is current). No records or settings values go in, only how the app is laid out.
import { readFileSync, writeFileSync } from 'node:fs';

export function buildGuide(root = '.') {
  const read = p => readFileSync(`${root}/${p}`, 'utf8');
  const prose = read('docs/assistant-guide.md').trim();

  const layout = read('src/components/Layout.tsx');
  const nav = layout.slice(layout.indexOf('const NAV:'), layout.indexOf('const OTHER:'));
  const menu = [];
  for (const section of nav.split(/\n\s*\{\s*\n\s*title: '/).slice(1)) {
    const title = section.slice(0, section.indexOf("'"));
    menu.push(`- ${title}`);
    // Each entry: its label, whether it's admin-only, and its tabs (on the same line or the next ones).
    const starts = [...section.matchAll(/\{ to: '[^']+', label: '[^']+', icon:/g)].map(m => m.index);
    const entries = starts.map((at, i) => section.slice(at, starts[i + 1]));
    for (const e of entries) {
      const label = e.match(/label: '([^']+)', icon:/)?.[1];
      const path = e.match(/^\{ to: '([^']+)'/)?.[1];
      if (!label) continue;
      const head = e.slice(0, e.indexOf('tabs:') > -1 ? e.indexOf('tabs:') : undefined);
      const tabsText = e.indexOf('tabs:') > -1 ? e.slice(e.indexOf('tabs:'), e.indexOf(']', e.indexOf('tabs:'))) : '';
      const tabs = [...tabsText.matchAll(/to: '([^']+)', label: '([^']+)'(, admin: true)?/g)].map(t => `${t[2]} (${t[1]})${t[3] ? ' (admins)' : ''}`);
      const who = /admin: true/.test(head) ? ' (admins)' : /platform: true/.test(head) ? ' (platform owner)' : '';
      menu.push(`  - ${label}${tabs.length ? '' : ` (${path})`}${who}${tabs.length ? `: tabs ${tabs.join(', ')}` : ''}`);
    }
  }

  const schemas = read('src/lib/schemas.ts');
  const forms = [];
  for (const block of schemas.matchAll(/export const (\w+Fields)(?:: Field\[\])? = \[([\s\S]*?)\n\];/g)) {
    const fields = [...block[2].matchAll(/\{ name: '(\w+)', label: '([^']+)'([^\n]*)/g)].map(f => {
      const help = f[3].match(/help: ['"]((?:[^'"\\]|\\.)*)['"]/)?.[1];
      return `  - ${f[2]}${/required: true/.test(f[3]) ? ' (required)' : ''}${help ? `: ${help.replace(/\\'/g, "'")}` : ''}`;
    });
    if (fields.length) forms.push(`- ${block[1].replace(/Fields$/, '').replace(/([A-Z])/g, ' $1').toLowerCase().trim()} form\n${fields.join('\n')}`);
  }

  const text = `${prose}\n\n## Menu (from the app; screen addresses in brackets)\n\n${menu.join('\n')}\n\n## Form fields (from the app)\n\n${forms.join('\n')}\n`;
  return `// Generated by scripts/build-assistant-guide.mjs from docs/assistant-guide.md, Layout.tsx and schemas.ts. Do not edit.\nexport const ASSISTANT_GUIDE = ${JSON.stringify(text)};\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync('supabase/functions/_shared/assistantGuide.ts', buildGuide());
  console.log('Wrote supabase/functions/_shared/assistantGuide.ts');
}
